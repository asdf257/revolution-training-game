// 显示某一天的课程或活动
function showDayCourse(day) {
    var dayNames = ['周一', '周二', '周三', '周四', '周五'];
    var dayIndex = day - 1;
    var contentArea = document.getElementById('dailyCourseContent');
    
    gameState.currentDay = day;
    
    // 更新标题显示
    document.getElementById('dailyWeekBadge').textContent = '第 ' + gameState.week + ' 周';
    
    var item = gameState.dailyCourses[dayIndex];
    
    if (!item) {
        // 该天没有项目，显示"你有自己的安排"
        showNoCourseMessage(day, dayNames[dayIndex]);
        return;
    }
    
    // 如果是课余活动，显示活动描述
    if (item.itemType === 'activity') {
        showActivityMessage(item, day, dayNames[dayIndex]);
        return;
    }
    
    // 该天有课程
    var course = item;
    var currentProgress = gameState.courseProgress[course.id] || 0;
    var schedule = courseContentSchedule[course.id];
    
    if (!schedule) {
        // 无内容配置，直接显示课程完成并进入下一天
        showCourseCompletionMessage(course, day, dayNames[dayIndex]);
        return;
    }
    
    // 检查是否需要显示导论
    var showIntro = schedule.intro === currentProgress + 1 && 
                     !gameState.shownCourseIntroIds[course.id] &&
                     courseIntroductions[course.id];
    
    // 检查是否需要显示互动
    var showScene = schedule.scene === currentProgress + 1 && 
                     !gameState.shownCourseSceneIds[course.id] &&
                     courseScenes[course.id];
    
    if (showIntro) {
        // 显示导论
        showCourseIntroModal(course, dayNames[dayIndex], { 
            course: course, 
            day: day,
            showScene: showScene 
        });
    } else if (showScene) {
        // 直接显示互动
        showCourseSceneModal(course, dayNames[dayIndex], { 
            course: course, 
            day: day 
        });
    } else {
        // 都不需要，显示课程完成
        showCourseCompletionMessage(course, day, dayNames[dayIndex]);
    }
}

