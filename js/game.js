// 完成当天课程（无特殊内容时）
function completeDayCourse(day) {
    var dayIndex = day - 1;
    var course = gameState.dailyCourses[dayIndex];
    
    if (course) {
        // 如果是军事课程，触发对应的小游戏
        if (course.type === 'military') {
            // 保存上下文，以便小游戏结束后继续流程
            gameState.pendingMilitaryGameContext = { course: course, day: day };
            // 根据课程ID启动对应的小游戏
            startMilitaryGame(course);
            return;
        }
        
        // 检查是否需要测验
        checkAndShowQuiz(course, day);
    } else {
        proceedToNextDay();
    }
}

