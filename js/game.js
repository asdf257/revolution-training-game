// 检查并显示测验（如果本次学习后完成requiredTimes）
function checkAndShowQuiz(course, day) {
    var requiredTimes = course.requiredTimes || 1;
    var currentProgress = gameState.courseProgress[course.id] || 0;
    var newProgress = currentProgress + 1;
    
    // 更新进度
    gameState.courseProgress[course.id] = newProgress;
    
    // 检查是否完成requiredTimes
    if (newProgress >= requiredTimes) {
        var schedule = courseContentSchedule[course.id];
        // 检查是否有测验题目
        if (schedule && schedule.quiz === newProgress && 
            courseQuizzes[course.id] && courseQuizzes[course.id].length > 0) {
            // 立即显示该课程的测验弹窗
            showDailyCourseQuiz(course, function() {
                if (gameState.completedCourseIds.indexOf(course.id) === -1) {
                    gameState.completedCourseIds.push(course.id);
                }
                proceedToNextDay();
            });
            return;
        }
        
        // 标记课程完成（达到 requiredTimes 后所有课程都加入已完成列表）
        if (gameState.completedCourseIds.indexOf(course.id) === -1) {
            gameState.completedCourseIds.push(course.id);
        }
    }
    
    proceedToNextDay();
}

