// 测验状态（当前正在进行的课程测验）
let quizState = null;

function startNextCourseQuiz() {
    if (!gameState.quizQueue || gameState.quizQueue.length === 0) {
        showSummaryAfterQuizzes();
        return;
    }
    const item = gameState.quizQueue.shift();
    const courseId = item.id;
    const courseName = item.name;
    const courseType = item.type;
    let questionList = courseQuizzes[courseId] || (courseId === 'l2' ? courseQuizzes.l1 : []);
    if (!questionList || questionList.length === 0) {
        startNextCourseQuiz();
        return;
    }
    questionList = questionList.slice();
    for (let i = questionList.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [questionList[i], questionList[j]] = [questionList[j], questionList[i]];
    }
    const numQuestions = Math.min(3, questionList.length);
    const questions = questionList.slice(0, numQuestions);
    quizState = { courseId, courseName, courseType, questions, index: 0, correctCount: 0, selected: null };
    document.getElementById('quizCourseName').textContent = courseName;
    document.getElementById('quizModal').classList.add('show');
    renderQuizQuestion();
}

function renderQuizQuestion() {
    if (!quizState) return;
    const total = quizState.questions.length;
    const idx = quizState.index;
    const item = quizState.questions[idx];
    
    // 使用index.html中的元素
    document.getElementById('quizProgress').textContent = `第 ${idx + 1} / ${total} 题`;
    document.getElementById('quizQuestion').textContent = item.q;
    document.getElementById('quizCourseName').textContent = quizState.courseName;
    
    const optsEl = document.getElementById('quizOpts');
    optsEl.innerHTML = '';
    item.opts.forEach((optText, i) => {
        const letter = String.fromCharCode(65 + i);
        const btn = document.createElement('button');
        btn.type = 'button';
        btn.className = 'quiz-opt-btn';
        btn.dataset.value = letter;
        btn.textContent = optText;
        btn.addEventListener('click', () => {
            if (btn.disabled) return;
            optsEl.querySelectorAll('.quiz-opt-btn').forEach(b => b.classList.remove('selected'));
            btn.classList.add('selected');
            quizState.selected = letter;
        });
        optsEl.appendChild(btn);
    });
    
    document.getElementById('quizResult').style.display = 'none';
    document.getElementById('quizSubmitBtn').style.display = 'inline-block';
    document.getElementById('quizNextBtn').style.display = 'none';
    quizState.selected = null;
}

function submitQuizAnswer() {
    if (!quizState || quizState.selected == null) return;
    const item = quizState.questions[quizState.index];
    const correct = item.correct;
    const isCorrect = quizState.selected === correct;
    if (isCorrect) {
        quizState.correctCount++;
        gameState.stats[quizState.courseType] = Math.min(gameState.maxStat, gameState.stats[quizState.courseType] + 1);
    }
    
    // 使用index.html中的元素
    const optsEl = document.getElementById('quizOpts');
    optsEl.querySelectorAll('.quiz-opt-btn').forEach(btn => {
        btn.disabled = true;
        if (btn.dataset.value === correct) btn.classList.add('correct');
        else if (btn.dataset.value === quizState.selected && !isCorrect) btn.classList.add('wrong');
    });
    
    const resultEl = document.getElementById('quizResult');
    const iconEl = document.getElementById('quizResultIcon');
    const textEl = document.getElementById('quizResultText');
    if (isCorrect) {
        iconEl.textContent = '✓';
        textEl.textContent = '回答正确！+1 ' + (statNames[quizState.courseType] || '');
    } else {
        iconEl.textContent = '✗';
        textEl.textContent = '正确答案是 ' + correct + '。';
    }
    resultEl.style.display = 'block';
    document.getElementById('quizSubmitBtn').style.display = 'none';
    document.getElementById('quizNextBtn').style.display = 'inline-block';
    document.getElementById('quizNextBtn').textContent = quizState.index + 1 < quizState.questions.length ? '下一题' : '完成测验';
    updateUI();

    // 2 秒后自动进入下一题或完成测验（若用户未手动点击「下一题」）
    if (quizState.autoNextTimer) clearTimeout(quizState.autoNextTimer);
    quizState.autoNextTimer = setTimeout(function () {
        quizState.autoNextTimer = null;
        nextQuizQuestion();
    }, 1000);
}

function nextQuizQuestion() {
    if (!quizState) return;
    if (quizState.autoNextTimer) {
        clearTimeout(quizState.autoNextTimer);
        quizState.autoNextTimer = null;
    }
    quizState.index++;
    if (quizState.index < quizState.questions.length) {
        quizState.selected = null;
        renderQuizQuestion();
        document.getElementById('quizSubmitBtn').style.display = 'inline-block';
        document.getElementById('quizNextBtn').style.display = 'none';
        return;
    }
    
    // 保存测验结果与后续步骤
    var summary = {
        courseName: quizState.courseName,
        correctCount: quizState.correctCount,
        total: quizState.questions.length,
        courseType: quizState.courseType
    };
    var onComplete = quizState.onComplete;
    var nextStep = function () {
        if (onComplete) {
            onComplete();
            return;
        }
        if (gameState.quizQueue && gameState.quizQueue.length > 0) {
            startNextCourseQuiz();
        } else {
            showSummaryAfterQuizzes();
        }
    };

    var modal = document.getElementById('quizModal');
    modal.classList.add('closing');
    quizState = null;
    setTimeout(function () {
        modal.classList.remove('show', 'closing');
        showQuizSummary(summary, nextStep);
    }, 720);
}

