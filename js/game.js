// 进行本周结算
function proceedWithWeekSummary() {
    // 记录本周变化前的属性
    const oldStats = { ...gameState.stats };
    const oldHealth = gameState.health;
    const currentWeek = gameState.week;

    // 图标映射
    const courseIcons = {
        political: '📕',
        military: '⚔️',
        labor: '🔨',
        mass: '👥'
    };

    // 分离课程和活动（从dailyCourses中分离，因为dailyCourses现在包含所有项目）
    var allItems = gameState.dailyCourses || gameState.selectedItems;
    var courses = [];
    var activities = [];
    for (var i = 0; i < allItems.length; i++) {
        if (allItems[i].itemType === 'course') {
            courses.push(allItems[i]);
        } else if (allItems[i].itemType === 'activity') {
            activities.push(allItems[i]);
        }
    }

    // 处理课程属性加成和精力值消耗
    courses.forEach(course => {
        // 根据当前精力值计算学习效率（学习前）
        const learningEfficiency = getLearningEfficiency(gameState.health);
        
        // 计算精力值消耗
        const healthCost = getCourseHealthCost(course);
        
        // 根据学习效率调整属性加成
        const actualPoints = Math.floor(course.points * learningEfficiency);
        
        // 消耗精力值
        gameState.health = Math.max(0, gameState.health - healthCost);
        
        // 增加属性（受学习效率影响）
        gameState.stats[course.type] += actualPoints;
        
        // 注意：课程进度和完成状态已在每日课程页面的 checkAndShowQuiz 中处理
    });

    // 应用课堂互动的属性加成
    if (gameState.courseSceneEffects) {
        Object.entries(gameState.courseSceneEffects).forEach(([stat, value]) => {
            if (gameState.stats[stat] !== undefined) {
                gameState.stats[stat] += value;
            }
        });
    }

    // 处理活动
    activities.forEach(activity => {
        // 应用活动效果
        Object.entries(activity.effect).forEach(([stat, value]) => {
            gameState.stats[stat] += value;
        });

        // 处理精力值恢复
        if (activity.healthRestore) {
            gameState.health = Math.min(gameState.maxHealth, gameState.health + activity.healthRestore);
        }
        
        // 处理精力值消耗（如果有）
        if (activity.healthCost) {
            gameState.health = Math.max(0, gameState.health - activity.healthCost);
        }
    });

    // 限制属性最大最小值
    Object.keys(gameState.stats).forEach(key => {
        if (gameState.stats[key] > gameState.maxStat) {
            gameState.stats[key] = gameState.maxStat;
        }
        if (gameState.stats[key] < gameState.minStat) {
            gameState.stats[key] = gameState.minStat;
        }
    });

    // 检查精力值，如果低于30，先退出课程页面再触发医院剧情
    if (gameState.health < 30) {
        exitDailyCoursePage();
        triggerHospitalEvent();
        return;
    }

    // 在课程内容页面内显示数值总结（不弹窗）
    var contentArea = document.getElementById('dailyCourseContent');
    if (!contentArea) return;

    var coursesHTML = '';
    for (var i = 0; i < courses.length; i++) {
        var course = courses[i];
        coursesHTML += '<div class="summary-course-item ' + course.type + '">' +
            '<div class="summary-course-icon ' + course.type + '">' + (courseIcons[course.type] || '📚') + '</div>' +
            '<div class="summary-course-content"><div class="summary-course-name">' + course.name + '</div></div>' +
            '</div>';
    }
    for (var j = 0; j < activities.length; j++) {
        var activity = activities[j];
        coursesHTML += '<div class="summary-course-item activity">' +
            '<div class="summary-course-icon activity">' + (activity.icon || '🎯') + '</div>' +
            '<div class="summary-course-content"><div class="summary-course-name">' + activity.name + '</div></div>' +
            '</div>';
    }

    var healthChange = gameState.health - oldHealth;
    var healthChangeClass = healthChange > 0 ? 'positive' : (healthChange < 0 ? 'negative' : '');
    var healthChangeText = healthChange > 0 ? '+' + healthChange : healthChange;
    var statsHTML = '<div class="summary-stat health-stat">' +
        '<div class="summary-stat-value">' + gameState.health + '</div>' +
        '<div class="summary-stat-change ' + healthChangeClass + '">' + healthChangeText + '</div>' +
        '<div class="summary-stat-name">💚 精力值</div></div>';
    Object.keys(gameState.stats).forEach(function(type) {
        var change = gameState.stats[type] - oldStats[type];
        var changeClass = change > 0 ? 'positive' : (change < 0 ? 'negative' : '');
        var changeText = change > 0 ? '+' + change : change;
        statsHTML += '<div class="summary-stat">' +
            '<div class="summary-stat-value">' + gameState.stats[type] + '</div>' +
            '<div class="summary-stat-change ' + changeClass + '">' + changeText + '</div>' +
            '<div class="summary-stat-name">' + statNames[type] + '</div></div>';
    });

    contentArea.innerHTML = '<div class="summary-inline">' +
        '<div class="summary-header">' +
            '<div class="summary-week-badge">第 ' + currentWeek + ' 周</div>' +
            '<h3 class="summary-title">📜 本周学习总结</h3>' +
        '</div>' +
        '<div class="summary-courses">' + coursesHTML + '</div>' +
        '<div class="summary-stats">' + statsHTML + '</div>' +
        '<button class="summary-btn" onclick="proceedAfterSummary()">继续下一周 →</button>' +
        '</div>';

    gameState.selectedItems = [];
    document.querySelectorAll('.course-card.selected').forEach(function(card) { card.classList.remove('selected'); });
    updateSelectionUI();
    updateUI();
    gameState.pendingRandomEvent = true;
    gameState.week++;
    updateUI();
}

