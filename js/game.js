// 将场景数据预处理为步骤数组
function buildVNSteps(sceneData) {
    var steps = [];
    
    if (sceneData.segments && sceneData.segments.length > 0) {
        for (var s = 0; s < sceneData.segments.length; s++) {
            var seg = sceneData.segments[s];
            if (seg.intro) steps.push({ type: 'narration', text: seg.intro, cssClass: 'vn-scene-intro' });
            if (seg.teacherIntro) steps.push({ type: 'narration', text: seg.teacherIntro, cssClass: 'vn-teacher-intro' });
            if (seg.teacherLine) steps.push({ type: 'narration', text: '「' + seg.teacherLine + '」', cssClass: 'vn-teacher-line' });
            
            if (seg.choices && seg.choices.length > 0) {
                steps.push({ type: 'choice', choices: seg.choices });
            } else if (seg.isQuiz && seg.quizOptions) {
                steps.push({ type: 'quiz', segment: seg });
            }
            
            if (seg.ending) {
                var endLines = seg.ending.split('\n').filter(function(l) { return l.trim(); });
                for (var e = 0; e < endLines.length; e++) {
                    steps.push({ type: 'ending', text: endLines[e], cssClass: 'vn-ending-line' });
                }
            }
        }
    } else {
        // 单段互动
        if (sceneData.intro) steps.push({ type: 'narration', text: sceneData.intro, cssClass: 'vn-scene-intro' });
        if (sceneData.teacherIntro) steps.push({ type: 'narration', text: sceneData.teacherIntro, cssClass: 'vn-teacher-intro' });
        if (sceneData.description) steps.push({ type: 'narration', text: sceneData.description, cssClass: 'vn-description' });
        if (sceneData.teacherLine) steps.push({ type: 'narration', text: '「' + sceneData.teacherLine + '」', cssClass: 'vn-teacher-line' });
        
        if (sceneData.choices && sceneData.choices.length > 0) {
            steps.push({ type: 'choice', choices: sceneData.choices });
        }
        
        if (sceneData.ending) {
            var endLines2 = sceneData.ending.split('\n').filter(function(l) { return l.trim(); });
            for (var e2 = 0; e2 < endLines2.length; e2++) {
                steps.push({ type: 'ending', text: endLines2[e2], cssClass: 'vn-ending-line' });
            }
        }
    }
    
    return steps;
}

