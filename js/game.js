// 推进到下一步
function vnAdvanceStep() {
    if (vnState.currentStep >= vnState.steps.length) {
        // 所有步骤完成
        vnFinish();
        return;
    }
    
    var step = vnState.steps[vnState.currentStep];
    vnState.currentStep++;
    
    if (step.type === 'narration' || step.type === 'ending') {
        vnShowText(step);
        // 如果是最后一步，显示结束提示
        if (vnState.currentStep >= vnState.steps.length) {
            vnShowFinishHint();
        }
    } else if (step.type === 'choice') {
        vnShowChoiceOverlay(step);
    } else if (step.type === 'quiz') {
        vnShowQuizOverlay(step);
    } else if (step.type === 'result') {
        // 结果文字直接显示（不需要点击）
        vnShowResultText(step);
        // 自动继续：如果下一步也是可展示内容，提示点击
        if (vnState.currentStep >= vnState.steps.length) {
            vnShowFinishHint();
        }
    } else if (step.type === 'effect') {
        vnShowEffectText(step);
        if (vnState.currentStep >= vnState.steps.length) {
            vnShowFinishHint();
        }
    }
}

